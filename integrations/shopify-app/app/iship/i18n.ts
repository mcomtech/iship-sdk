const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en, th };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translator(locale: Locale): Translate {
  const messages = MESSAGES[locale];
  return (key, vars) =>
    (messages[key] ?? en[key]).replace(/\{(\w+)\}/g, (match, name: string) =>
      vars && name in vars ? String(vars[name]) : match,
    );
}

/** Thai when Shopify's locale or the browser asks for it, English otherwise. */
export function localeFrom(request: Request): Locale {
  const fromShopify = new URL(request.url).searchParams.get("locale");
  const wanted = fromShopify ?? request.headers.get("accept-language") ?? "";
  return /^th\b/i.test(wanted.trim()) ? "th" : "en";
}

/** The translator for the current page. Reads the locale the app layout loaded. */
export function useT(): Translate {
  const data = useRouteLoaderData("routes/app") as { locale?: Locale } | undefined;
  return translator(data?.locale ?? "en");
}

